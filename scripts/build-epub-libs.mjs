// Embeds the EPUB reader's two libraries (jszip, epub.js) in the app, so the reader page needs no network and loads
// nothing from a CDN. Reads them from node_modules and writes src/lib/epubLibs.generated.ts.
// Run `npm run build:epub-libs` after changing either dependency; a test fails if the file is out of date.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = path.join(root, 'src', 'lib', 'epubLibs.generated.ts');

const read = (file) => fs.readFileSync(path.join(root, 'node_modules', file), 'utf8');
const version = (pkg) => JSON.parse(read(`${pkg}/package.json`)).version;

// A library is pasted into an inline <script>, so it must not contain anything the HTML parser would treat specially.
const HAZARDS = /<\/script|<!--|<script/i;

// A JavaScript string literal for `text`, safe to paste into a module (JSON also needs U+2028/9 escaped in older engines).
const LS = String.fromCharCode(0x2028);
const PS = String.fromCharCode(0x2029);
const literal = (text) => JSON.stringify(text).split(LS).join('\\u2028').split(PS).join('\\u2029');

export function render() {
  const libs = [
    ['JSZIP_SRC', 'jszip', 'jszip/dist/jszip.min.js'],
    ['EPUBJS_SRC', 'epubjs', 'epubjs/dist/epub.min.js'],
  ];
  const lines = [
    `// Generated by scripts/build-epub-libs.mjs from node_modules (${libs.map(([, pkg]) => `${pkg} ${version(pkg)}`).join(', ')}).`,
    '// Do not edit. After changing either dependency, run `npm run build:epub-libs`.',
  ];
  for (const [name, , file] of libs) {
    const src = read(file);
    if (HAZARDS.test(src)) throw new Error(`${file} contains markup that cannot be pasted into an inline <script>`);
    lines.push(`export const ${name} = ${literal(src)};`);
  }
  return `${lines.join('\n')}\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(OUT, render());
  console.log(`Wrote ${path.relative(root, OUT)} (${(fs.statSync(OUT).size / 1024).toFixed(0)} KB)`);
}
