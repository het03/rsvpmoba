// Collects the licence notices of everything the app ships, for the in-app "Open-source licences" screen:
// every production dependency (and its dependencies) in node_modules, with its copyright lines and licence text.
// Packages whose licence text is identical (ignoring copyright lines) are grouped, so each text appears once.
// Run `npm run build:notices` after changing dependencies; a test fails if src/lib/notices.generated.ts is out of date.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = path.join(root, 'src', 'lib', 'notices.generated.ts');

const readJson = (file) => JSON.parse(fs.readFileSync(file, 'utf8'));

function findPackageDir(fromDir, name) {
  let dir = fromDir;
  for (;;) {
    const candidate = path.join(dir, 'node_modules', name);
    if (fs.existsSync(path.join(candidate, 'package.json'))) return candidate;
    const parent = path.dirname(dir);
    if (parent === dir || !parent.startsWith(root)) return null;
    dir = parent;
  }
}

// Production dependencies of the app, and theirs, as they are installed. Dev tools are not shipped, so they are left out.
function shippedPackages() {
  const found = new Map(); // real directory -> package.json
  const visit = (dir) => {
    const real = fs.realpathSync(dir);
    if (found.has(real)) return;
    const pkg = readJson(path.join(real, 'package.json'));
    found.set(real, pkg);
    for (const name of Object.keys({ ...pkg.dependencies, ...pkg.optionalDependencies })) {
      const child = findPackageDir(real, name);
      if (child) visit(child);
    }
  };
  const rootPkg = readJson(path.join(root, 'package.json'));
  for (const name of Object.keys(rootPkg.dependencies ?? {})) {
    const dir = findPackageDir(root, name);
    if (dir) visit(dir);
  }
  return [...found.entries()].map(([dir, pkg]) => ({ dir, pkg }));
}

const LICENSE_FILE = /^(licen[sc]e|copying|unlicense)([-_.].*)?$/i;
const COPYRIGHT = /^\s*(copyright\b|\(c\)|©)/i;

const normalize = (text) => text
  .split(/\r?\n/)
  .filter((line) => !COPYRIGHT.test(line))
  .join(' ')
  .toLowerCase()
  .replace(/\s+/g, ' ')
  .trim();

const spdx = (pkg) => {
  const l = pkg.license ?? (pkg.licenses && pkg.licenses.map((x) => x.type).join(' OR '));
  return typeof l === 'object' && l ? l.type : l || 'UNKNOWN';
};

export function collect() {
  const groups = new Map(); // normalized text -> { text, ids, packages }
  const noText = new Map(); // spdx id -> packages with no licence file
  const seen = new Set();

  for (const { dir, pkg } of shippedPackages().sort((a, b) => (a.pkg.name + a.pkg.version).localeCompare(b.pkg.name + b.pkg.version))) {
    const label = `${pkg.name} ${pkg.version}`;
    if (seen.has(label)) continue;
    seen.add(label);
    const id = spdx(pkg);

    const files = fs.readdirSync(dir).filter((f) => LICENSE_FILE.test(f) && fs.statSync(path.join(dir, f)).isFile()).sort();
    if (files.length === 0) {
      if (!noText.has(id)) noText.set(id, []);
      noText.get(id).push(label);
      continue;
    }
    for (const file of files) {
      const text = fs.readFileSync(path.join(dir, file), 'utf8').replace(/\r\n/g, '\n').trim();
      if (!text) continue;
      const key = normalize(text);
      if (!groups.has(key)) groups.set(key, { text, ids: new Set(), packages: [] });
      const g = groups.get(key);
      g.ids.add(id);
      const copyright = text.split('\n').filter((l) => COPYRIGHT.test(l)).slice(0, 3).map((l) => l.trim().replace(/\s+/g, ' '));
      g.packages.push({ name: label, file: file === files[0] && files.length === 1 ? '' : file, copyright });
    }
  }

  const licences = [...groups.values()]
    .map((g) => ({
      title: [...g.ids].sort().join(', '),
      text: g.text,
      packages: g.packages.map((p) => ({ name: p.name + (p.file ? ` (${p.file})` : ''), copyright: p.copyright })),
    }))
    .sort((a, b) => b.packages.length - a.packages.length || a.title.localeCompare(b.title));

  const unlisted = [...noText.entries()].map(([id, packages]) => ({ id, packages })).sort((a, b) => b.packages.length - a.packages.length);
  return { licences, unlisted };
}

// A JavaScript string literal safe to paste into a module (U+2028/9 are built, not typed, so this file stays clean).
const LS = String.fromCharCode(0x2028);
const PS = String.fromCharCode(0x2029);
const json = (value) => JSON.stringify(value).split(LS).join('\\u2028').split(PS).join('\\u2029');

export function render() {
  const { licences, unlisted } = collect();
  return [
    '// Generated by scripts/build-notices.mjs from node_modules. Do not edit; run `npm run build:notices`.',
    'export type LicenceGroup = { title: string; text: string; packages: { name: string; copyright: string[] }[] };',
    'export type UnlistedGroup = { id: string; packages: string[] };',
    `export const LICENCES: LicenceGroup[] = ${json(licences)};`,
    `export const UNLISTED: UnlistedGroup[] = ${json(unlisted)};`,
    '',
  ].join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { licences, unlisted } = collect();
  fs.writeFileSync(OUT, render());
  const packages = licences.reduce((n, g) => n + g.packages.length, 0);
  console.log(`Wrote ${path.relative(root, OUT)} (${(fs.statSync(OUT).size / 1024).toFixed(0)} KB): ${licences.length} licence texts, ${packages} licence files, ${unlisted.reduce((n, u) => n + u.packages.length, 0)} packages with no licence file`);
  for (const u of unlisted) console.log(`  no licence file (${u.id}): ${u.packages.join(', ')}`);
}
